#include <nvforest/cuda_stream.hpp>
#include <nvforest/decision_forest.hpp>
#include <nvforest/detail/copy.hpp>
#include <nvforest/detail/cuda_check.hpp>
#include <nvforest/detail/gpu_support.hpp>
#include <nvforest/detail/index_type.hpp>
#include <nvforest/device_type.hpp>
#include <nvforest/infer_kind.hpp>

#ifdef NVFOREST_ENABLE_GPU
#include <cuda_runtime_api.h>
#endif

#include <cstddef>
#include <functional>
#include <stdexcept>
#include <type_traits>
#include <utility>
#include <variant>

namespace nvforest {

/**
 * A model used for performing inference with nvForest
 *
 * This struct is a wrapper for all variants of decision_forest supported by a
 * standard nvForest build.
 */
struct forest_model {
  /** Wrap a decision_forest in a full forest_model object */
  forest_model(decision_forest_variant&& forest = decision_forest_variant{})
    : decision_forest_{std::move(forest)}
  {
  }

  /** The number of features per row expected by the model */
  auto num_features()
  {
    return std::visit([](auto&& concrete_forest) { return concrete_forest.num_features(); },
                      decision_forest_);
  }

  /** The number of outputs per row generated by the model for the given type of inference */
  auto num_outputs(infer_kind inference_kind = infer_kind::default_kind)
  {
    return std::visit(
      [inference_kind](auto&& concrete_forest) {
        return concrete_forest.num_outputs(inference_kind);
      },
      decision_forest_);
  }

  /** The number of trees in the model */
  auto num_trees()
  {
    return std::visit([](auto&& concrete_forest) { return concrete_forest.num_trees(); },
                      decision_forest_);
  }

  /** Whether or not leaf nodes use vector outputs */
  auto has_vector_leaves()
  {
    return std::visit([](auto&& concrete_forest) { return concrete_forest.has_vector_leaves(); },
                      decision_forest_);
  }

  /** The operation used for postprocessing all outputs for a single row */
  auto row_postprocessing()
  {
    return std::visit([](auto&& concrete_forest) { return concrete_forest.row_postprocessing(); },
                      decision_forest_);
  }

  /** Setter for row_postprocessing() */
  void set_row_postprocessing(row_op val)
  {
    return std::visit(
      [&val](auto&& concrete_forest) { concrete_forest.set_row_postprocessing(val); },
      decision_forest_);
  }

  /** The operation used for postprocessing each element of the output for a
   * single row */
  auto elem_postprocessing()
  {
    return std::visit([](auto&& concrete_forest) { return concrete_forest.elem_postprocessing(); },
                      decision_forest_);
  }

  /** The type of memory (device/host) where the model is stored */
  auto memory_type()
  {
    return std::visit([](auto&& concrete_forest) { return concrete_forest.memory_type(); },
                      decision_forest_);
  }

  /** The ID of the device on which this model is loaded */
  auto device_index()
  {
    return std::visit([](auto&& concrete_forest) { return concrete_forest.device_index(); },
                      decision_forest_);
  }

  /** Whether or not model is loaded at double precision */
  auto is_double_precision()
  {
    return std::visit(
      [](auto&& concrete_forest) {
        return std::is_same_v<typename std::remove_reference_t<decltype(concrete_forest)>::io_type,
                              double>;
      },
      decision_forest_);
  }

  /**
   * Perform inference on given input
   *
   * @param[in] stream A nvforest::cuda_stream, which (on GPU-enabled builds) is
   * a transparent wrapper for the cudaStream_t or (on CPU-only builds) a
   * CUDA-free placeholder object.
   * @param[out] output The buffer where model output should be stored.
   * This must be of size at least ROWS x num_outputs(predict_type).
   * @param[in] input The buffer containing input data.
   * @param[in] predict_type Type of inference to perform. Defaults to summing
   * the outputs of all trees and produce an output per row. If set to
   * "per_tree", we will instead output all outputs of individual trees.
   * If set to "leaf_id", we will output the integer ID of the leaf node
   * for each tree.
   * @param[in] specified_chunk_size: Specifies the mini-batch size for
   * processing. This has different meanings on CPU and GPU, but on GPU it
   * corresponds to the number of rows evaluated per inference iteration
   * on a single block. It can take on any power of 2 from 1 to 32, and
   * runtime performance is quite sensitive to the value chosen. In general,
   * larger batches benefit from higher values, but it is hard to predict the
   * optimal value a priori. If omitted, a heuristic will be used to select a
   * reasonable value. On CPU, this argument can generally just be omitted.
   */
  template <typename io_t>
  void predict(cuda_stream stream,
               buffer<io_t>& output,
               buffer<io_t> const& input,
               infer_kind predict_type                        = infer_kind::default_kind,
               std::optional<index_type> specified_chunk_size = std::nullopt)
  {
    std::visit(
      [this, predict_type, &output, &input, &stream, &specified_chunk_size](
        auto&& concrete_forest) {
        using model_io_t = typename std::remove_reference_t<decltype(concrete_forest)>::io_type;
        if constexpr (std::is_same_v<model_io_t, io_t>) {
          if (output.memory_type() == memory_type() && input.memory_type() == memory_type()) {
            concrete_forest.predict(output, input, stream, predict_type, specified_chunk_size);
          } else {
            auto row_count = input.size() / num_features();
            auto buffer_in = buffer<io_t>{};
            if (input.memory_type() != memory_type()) {
              buffer_in =
                buffer<io_t>{row_count * num_features(), memory_type(), device_index(), stream};
              copy<detail::DEBUG_ENABLED>(buffer_in, input, 0, 0, buffer_in.size(), stream);
            } else {
              buffer_in = buffer<io_t>{
                input.data(), row_count * num_features(), memory_type(), input.device_index()};
            }
            auto buffer_out = buffer<io_t>{};
            if (output.memory_type() != memory_type()) {
              buffer_out = buffer<io_t>{
                row_count * num_outputs(predict_type), memory_type(), device_index(), stream};
            } else {
              buffer_out = buffer<io_t>{output.data(),
                                        row_count * num_outputs(predict_type),
                                        memory_type(),
                                        output.device_index()};
            }
            concrete_forest.predict(
              buffer_out, buffer_in, stream, predict_type, specified_chunk_size);
            if (output.memory_type() != memory_type()) {
              copy<detail::DEBUG_ENABLED>(output, buffer_out, 0, 0, buffer_out.size(), stream);
            }
          }
        } else {
          throw type_error("Input type does not match model_type");
        }
      },
      decision_forest_);
  }

  /**
   * Perform inference on given input, using multiple CUDA streams.
   * A stream pool lets you overlap memory transfers with partitioned inference.
   *
   * @param[in] stream_pool_next A callback function that returns a CUDA stream
   * from the pool.
   * @param[in] stream_pool_size The number of CUDA streams in the pool. This
   * must be greater than zero.
   * @param[out] output The buffer where model output should be stored. If
   * this buffer is on host while the model is on device or vice versa,
   * work will be distributed across available streams to copy the data back
   * to this output location. This must be of size at least ROWS x num_outputs(predict_type).
   * @param[in] input The buffer containing input data. If
   * this buffer is on host while the model is on device or vice versa,
   * work will be distributed across available streams to copy the input data
   * to the appropriate location and perform inference.
   * @param[in] predict_type Type of inference to perform. Defaults to summing
   * the outputs of all trees and produce an output per row. If set to
   * "per_tree", we will instead output all outputs of individual trees.
   * If set to "leaf_id", we will output the integer ID of the leaf node
   * for each tree.
   * @param[in] specified_chunk_size: Specifies the mini-batch size for
   * processing. This has different meanings on CPU and GPU, but on GPU it
   * corresponds to the number of rows evaluated per inference iteration
   * on a single block. It can take on any power of 2 from 1 to 32, and
   * runtime performance is quite sensitive to the value chosen. In general,
   * larger batches benefit from higher values, but it is hard to predict the
   * optimal value a priori. If omitted, a heuristic will be used to select a
   * reasonable value. On CPU, this argument can generally just be omitted.
   */
  template <typename io_t>
  void predict(std::function<cuda_stream()> const& stream_pool_next,
               std::size_t stream_pool_size,
               buffer<io_t>& output,
               buffer<io_t> const& input,
               infer_kind predict_type                        = infer_kind::default_kind,
               std::optional<index_type> specified_chunk_size = std::nullopt)
  {
    if (stream_pool_size == 0) {
      throw std::invalid_argument("stream_pool_size must be greater than zero");
    }
    std::visit(
      [this,
       predict_type,
       &stream_pool_next,
       stream_pool_size,
       &output,
       &input,
       &specified_chunk_size](auto&& concrete_forest) {
        using model_io_t = std::remove_reference_t<decltype(concrete_forest)>::io_type;
        if constexpr (std::is_same_v<model_io_t, io_t>) {
          if (output.memory_type() == memory_type() && input.memory_type() == memory_type()) {
            concrete_forest.predict(
              output, input, stream_pool_next(), predict_type, specified_chunk_size);
          } else {
            auto constexpr static const MIN_CHUNKS_PER_PARTITION = std::size_t{64};
            auto constexpr static const MAX_CHUNK_SIZE           = std::size_t{64};

            auto row_count = input.size() / num_features();
            auto partition_size =
              std::max(detail::ceildiv(row_count, stream_pool_size),
                       specified_chunk_size.value_or(MAX_CHUNK_SIZE) * MIN_CHUNKS_PER_PARTITION);
            auto partition_count = detail::ceildiv(row_count, partition_size);
            for (auto i = std::size_t{}; i < partition_count; ++i) {
              auto stream = stream_pool_next();
              auto rows_in_this_partition =
                std::min(partition_size, row_count - i * partition_size);
              auto partition_in = buffer<io_t>{};
              if (input.memory_type() != memory_type()) {
                partition_in = buffer<io_t>{
                  rows_in_this_partition * num_features(), memory_type(), device_index(), stream};
                copy<detail::DEBUG_ENABLED>(partition_in,
                                            input,
                                            0,
                                            i * partition_size * num_features(),
                                            partition_in.size(),
                                            stream);
              } else {
                partition_in = buffer<io_t>{input.data() + i * partition_size * num_features(),
                                            rows_in_this_partition * num_features(),
                                            memory_type(),
                                            input.device_index()};
              }
              auto partition_out = buffer<io_t>{};
              if (output.memory_type() != memory_type()) {
                partition_out = buffer<io_t>{rows_in_this_partition * num_outputs(predict_type),
                                             memory_type(),
                                             device_index(),
                                             stream};
              } else {
                partition_out =
                  buffer<io_t>{output.data() + i * partition_size * num_outputs(predict_type),
                               rows_in_this_partition * num_outputs(predict_type),
                               memory_type(),
                               output.device_index()};
              }
              concrete_forest.predict(
                partition_out, partition_in, stream, predict_type, specified_chunk_size);
              if (output.memory_type() != memory_type()) {
                copy<detail::DEBUG_ENABLED>(output,
                                            partition_out,
                                            i * partition_size * num_outputs(predict_type),
                                            0,
                                            partition_out.size(),
                                            stream);
              }
            }
          }
        } else {
          throw type_error("Input type does not match model_type");
        }
      },
      decision_forest_);
  }

  /**
   * Perform inference on given input
   *
   * @param[in] stream A nvforest::cuda_stream, which (on GPU-enabled builds) is
   * a transparent wrapper for the cudaStream_t or (on CPU-only builds) a
   * CUDA-free placeholder object. If this argument is cudaStream_t, ensure
   * that this stream is associated with the same GPU device as the model object.
   * @param[out] output Pointer to the memory location where output should end
   * up
   * @param[in] input Pointer to the input data
   * @param[in] num_rows Number of rows in input
   * @param[in] out_mem_type The memory type (device/host) of the output
   * buffer
   * @param[in] in_mem_type The memory type (device/host) of the input buffer
   * @param[in] predict_type Type of inference to perform. Defaults to summing
   * the outputs of all trees and produce an output per row. If set to
   * "per_tree", we will instead output all outputs of individual trees.
   * If set to "leaf_id", we will output the integer ID of the leaf node
   * for each tree.
   * @param[in] specified_chunk_size: Specifies the mini-batch size for
   * processing. This has different meanings on CPU and GPU, but on GPU it
   * corresponds to the number of rows evaluated per inference iteration
   * on a single block. It can take on any power of 2 from 1 to 32, and
   * runtime performance is quite sensitive to the value chosen. In general,
   * larger batches benefit from higher values, but it is hard to predict the
   * optimal value a priori. If omitted, a heuristic will be used to select a
   * reasonable value. On CPU, this argument can generally just be omitted.
   */
  template <typename io_t>
  void predict(cuda_stream stream,
               io_t* output,
               io_t* input,
               std::size_t num_rows,
               device_type out_mem_type,
               device_type in_mem_type,
               infer_kind predict_type                        = infer_kind::default_kind,
               std::optional<index_type> specified_chunk_size = std::nullopt)
  {
    int current_device_id;
    if (out_mem_type == device_type::gpu || in_mem_type == device_type::gpu) {
#ifdef NVFOREST_ENABLE_GPU
      detail::cuda_check(cudaGetDevice(&current_device_id));
#else
      throw detail::gpu_unsupported("Tried to use GPU memory in CPU-only build");
#endif
    } else {
      current_device_id = -1;
    }
    auto out_buffer =
      buffer{output, num_rows * num_outputs(predict_type), out_mem_type, current_device_id};
    auto in_buffer = buffer{input, num_rows * num_features(), in_mem_type, current_device_id};
    predict(stream, out_buffer, in_buffer, predict_type, specified_chunk_size);
  }

  /**
   * Perform inference on given input, using multiple CUDA streams.
   * A stream pool lets you overlap memory transfers with partitioned inference.
   *
   * @param[in] stream_pool_next A callback function that returns a CUDA stream
   * from the pool.
   * @param[in] stream_pool_size The number of CUDA streams in the pool. This
   * must be greater than zero.
   * @param[out] output Pointer to the memory location where output should end
   * up
   * @param[in] input Pointer to the input data
   * @param[in] num_rows Number of rows in input
   * @param[in] out_mem_type The memory type (device/host) of the output
   * buffer
   * @param[in] in_mem_type The memory type (device/host) of the input buffer
   * @param[in] predict_type Type of inference to perform. Defaults to summing
   * the outputs of all trees and produce an output per row. If set to
   * "per_tree", we will instead output all outputs of individual trees.
   * If set to "leaf_id", we will output the integer ID of the leaf node
   * for each tree.
   * @param[in] specified_chunk_size: Specifies the mini-batch size for
   * processing. This has different meanings on CPU and GPU, but on GPU it
   * corresponds to the number of rows evaluated per inference iteration
   * on a single block. It can take on any power of 2 from 1 to 32, and
   * runtime performance is quite sensitive to the value chosen. In general,
   * larger batches benefit from higher values, but it is hard to predict the
   * optimal value a priori. If omitted, a heuristic will be used to select a
   * reasonable value. On CPU, this argument can generally just be omitted.
   */
  template <typename io_t>
  void predict(std::function<cuda_stream()> const& stream_pool_next,
               std::size_t stream_pool_size,
               io_t* output,
               io_t* input,
               std::size_t num_rows,
               device_type out_mem_type,
               device_type in_mem_type,
               infer_kind predict_type                        = infer_kind::default_kind,
               std::optional<index_type> specified_chunk_size = std::nullopt)
  {
    int current_device_id;
    if (out_mem_type == device_type::gpu || in_mem_type == device_type::gpu) {
#ifdef NVFOREST_ENABLE_GPU
      detail::cuda_check(cudaGetDevice(&current_device_id));
#else
      throw detail::gpu_unsupported("Tried to use GPU memory in CPU-only build");
#endif
    } else {
      current_device_id = -1;
    }
    auto out_buffer =
      buffer{output, num_rows * num_outputs(predict_type), out_mem_type, current_device_id};
    auto in_buffer = buffer{input, num_rows * num_features(), in_mem_type, current_device_id};
    predict(stream_pool_next,
            stream_pool_size,
            out_buffer,
            in_buffer,
            predict_type,
            specified_chunk_size);
  }

 private:
  decision_forest_variant decision_forest_;
};

}  // namespace nvforest
